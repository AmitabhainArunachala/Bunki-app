const scopeSelector = (sel) => {
  const s = sel.trim();
  if (s === ':root' || s === 'body' || s === 'html' || s === 'html,body')
    return '#drift-layer';
  if (s === '*') return '#drift-layer, #drift-layer *';
  return s
    .split(',')
    .map((part) => `#drift-layer ${part.trim()}`)
    .join(',\n');
};
